"""Score the Python and JS engines on evals/dataset.jsonl and write evals/SCORECARD.md.

A prediction counts as correct when its type matches and it covers the labeled
span (overlap of at least 80% of the label). Run: python evals/run.py
Exits non-zero if any type drops below the floors in FLOORS (used by CI).
"""

import json
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE.parent / "core" / "python"))
from pii_firewall import ENTITY_TYPES, detect  # noqa: E402

# CI fails if precision or recall for a type falls below these.
FLOORS = {"SSN": (0.95, 0.85), "CREDIT_CARD": (0.98, 0.98), "EMAIL": (0.98, 0.98), "PHONE": (0.95, 0.95),
          "PERSON": (0.95, 0.80), "ADDRESS": (0.95, 0.80)}


def load():
    return [json.loads(line) for line in (HERE / "dataset.jsonl").read_text().splitlines()]


def match(pred, gold):
    if pred["type"] != gold["type"]:
        return False
    overlap = min(pred["end"], gold["end"]) - max(pred["start"], gold["start"])
    return overlap >= 0.8 * (gold["end"] - gold["start"])


def score(data, preds):
    tp, fp, fn = defaultdict(int), defaultdict(int), defaultdict(int)
    for ex in data:
        gold, pred = ex["spans"], preds[ex["id"]]
        used = set()
        for p in pred:
            hit = next((i for i, g in enumerate(gold) if i not in used and match(p, g)), None)
            if hit is None:
                fp[p["type"]] += 1
            else:
                used.add(hit)
                tp[p["type"]] += 1
        for i, g in enumerate(gold):
            if i not in used:
                fn[g["type"]] += 1
    rows = {}
    for t in ENTITY_TYPES:
        P = tp[t] / (tp[t] + fp[t]) if tp[t] + fp[t] else 1.0
        R = tp[t] / (tp[t] + fn[t]) if tp[t] + fn[t] else 1.0
        F = 2 * P * R / (P + R) if P + R else 0.0
        rows[t] = {"precision": P, "recall": R, "f1": F, "support": tp[t] + fn[t], "false_pos": fp[t]}
    return rows


def main():
    data = load()
    py = {ex["id"]: [{"type": e.type, "start": e.start, "end": e.end} for e in detect(ex["text"])] for ex in data}
    out = subprocess.run(["node", str(HERE / "predict.js")], capture_output=True, text=True, check=True).stdout
    js = {d["id"]: d["spans"] for d in map(json.loads, out.splitlines())}

    py_rows = score(data, py)
    parity = sum(py[i] == js[i] for i in py) / len(py)

    lines = [
        "# Detection scorecard",
        "",
        (
            f"{len(data)} synthetic examples (`evals/dataset.jsonl`, generated by `evals/generate.py`, seed 7). "
            "Includes decoys (order numbers, ZIPs, prices, meeting dates) and hard cases the engine is known to miss."
        ),
        "",
        "| Type | Precision | Recall | F1 | Labeled | False positives |",
        "|---|---|---|---|---|---|",
    ]
    for t, r in py_rows.items():
        lines.append(f"| {t} | {r['precision']:.1%} | {r['recall']:.1%} | {r['f1']:.1%} | {r['support']} | {r['false_pos']} |")
    lines += [
        "",
        f"**Python and JavaScript engines agree on {parity:.1%} of examples.**",
        "",
        "## Known gaps (by design of the hard cases)",
        "",
        (
            "- Lowercase names the dictionary doesn't know, with no cue around them "
            "(\"sibonelo guliwe agreed to the terms\"), are missed."
        ),
        "- Addresses without a house number and street suffix (common in India: \"Flat 302, Sai Residency, Madhapur\") are missed unless a cue like \"ship to\" comes first.",
        (
            "- Names in this set come from 14 languages **not** used to build the name dictionary. "
            "Addresses and other types come from templates written alongside the detectors, so expect "
            "lower accuracy on real, messy text. Contributions of new hard cases are welcome."
        ),
        "",
        "Regenerate with `python evals/generate.py && python evals/run.py`.",
    ]
    (HERE / "SCORECARD.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))

    failed = [t for t, (p, r) in FLOORS.items() if py_rows[t]["precision"] < p or py_rows[t]["recall"] < r]
    if failed or parity < 1.0:
        print(f"\nFAILED floors: {failed}  parity: {parity:.3f}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
